/**
 * Genera el subconjunto de la colección `lucide` usado por KunUI.
 *
 * - Lee el mapa de alias (`src/icons/index.ts`, `kunIconAliases`).
 * - Extrae solo los íconos referenciados desde `@iconify-json/lucide`.
 * - Escribe `src/icons/lucide.generated.ts` con un `IconifyJSON` filtrado que
 *   la librería registra en runtime (`addCollection`) para resolver sus íconos
 *   propios sin tocar la red.
 *
 * Uso: `pnpm run generate:icons` (o `node scripts/generate-icons.ts`).
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { createRequire } from 'node:module';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const rootDir = path.resolve(__dirname, '..');

const aliasesPath = path.join(rootDir, 'src', 'icons', 'index.ts');
const outPath = path.join(rootDir, 'src', 'icons', 'lucide.generated.ts');
const collectionPath = path.join(rootDir, 'node_modules', '@iconify-json', 'lucide', 'icons.json');

interface IconifyJSON {
  prefix: string;
  icons: Record<string, { body: string }>;
  aliases?: Record<string, unknown>;
  width?: number;
  height?: number;
  lastModified?: number;
}

async function loadAliases(): Promise<Record<string, string>> {
  const mod = (await import(pathToFileURL(aliasesPath).href)) as {
    kunIconAliases?: Record<string, string>;
  };
  if (!mod.kunIconAliases || typeof mod.kunIconAliases !== 'object') {
    throw new Error(`No se pudo leer 'kunIconAliases' desde ${aliasesPath}`);
  }
  return mod.kunIconAliases;
}

async function main(): Promise<void> {
  const require = createRequire(import.meta.url);
  const collection = require(collectionPath) as IconifyJSON;
  const aliases = await loadAliases();

  const wanted = new Set<string>();
  for (const [alias, name] of Object.entries(aliases)) {
    const [prefix, icon] = name.includes(':')
      ? name.split(':')
      : [collection.prefix, name.replace(`${collection.prefix}-`, '')];
    if (prefix !== collection.prefix) {
      throw new Error(`Alias '${alias}' apunta a '${name}', fuera de la colección '${collection.prefix}'.`);
    }
    if (!icon) throw new Error(`Alias '${alias}' tiene un nombre Iconify vacío ('${name}').`);
    wanted.add(icon);
  }

  const icons: Record<string, { body: string }> = {};
  const missing: string[] = [];
  for (const icon of [...wanted].sort()) {
    const data = collection.icons[icon];
    if (!data) {
      missing.push(icon);
      continue;
    }
    icons[icon] = { body: data.body };
  }
  if (missing.length) {
    throw new Error(
      `Íconos inexistentes en '${collection.prefix}': ${missing.join(', ')}. Revisá src/icons/index.ts.`,
    );
  }

  const subset: IconifyJSON = {
    prefix: collection.prefix,
    icons,
    width: collection.width ?? 24,
    height: collection.height ?? 24,
  };
  if (collection.lastModified) subset.lastModified = collection.lastModified;

  const banner = [
    '// AUTO-GENERATED by scripts/generate-icons.ts — do not edit by hand.',
    `// Subconjunto '${collection.prefix}' usado por KunUI (${Object.keys(icons).length} íconos).`,
    '// Regenerar: `pnpm run generate:icons`.',
    '',
    "import type { IconifyJSON } from '@iconify/vue';",
    '',
  ].join('\n');

  const json = JSON.stringify(subset, null, 2);
  const content = `${banner}export const lucideSubset: IconifyJSON = ${json};\n`;

  fs.writeFileSync(outPath, content, 'utf8');
  console.log(`✓ ${path.relative(rootDir, outPath)} (${Object.keys(icons).length} íconos de '${collection.prefix}')`);
}

main().catch((err) => {
  console.error('✗ generate-icons:', err instanceof Error ? err.message : err);
  process.exit(1);
});
